#!/usr/bin/env python3
"""Generates PLACEHOLDER audio: one sine-tone clip per ayah, no recitation.

Real recordings come from a qualified qari (#18). Until then, these tones let
the app and its tests exercise the whole player (playlist, gaps, fades,
pause and resume) without any third-party recording entering the repository.

Each surah has its own pitch, so you can hear which surah is playing; each
ayah is 1.0-1.5 s long, with a short higher blip at the end so ayah
boundaries are audible. Al-Fatiha's tone is the lowest.

The audio files are NOT committed (binary files stay out of git); only
catalog.json is. Run this once after cloning, before `flutter test` or
`flutter run`; the Android build runs it by itself when files are missing.

Output (paths relative to the repository root):
    app/assets/audio/placeholder/SSSAAA.wav   (16 kHz mono 16-bit PCM)
    app/assets/audio/placeholder/catalog.json (committed; regenerated identically)
    app/assets/audio/silence_10s.wav          (8 kHz mono, used by the player for gaps)

Usage:
    python3 scripts/make_placeholder_audio.py              # (re)generate everything
    python3 scripts/make_placeholder_audio.py --if-missing # only if a file is missing

Python 3 standard library only (wave, struct, math, json). No network, no
ffmpeg. The output is deterministic: the same bytes on every run and machine.
About 3.9 MB in total.
"""

from __future__ import annotations

import argparse
import json
import math
import struct
import sys
import wave
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ASSETS = REPO / "app" / "assets" / "audio"
OUT_DIR = ASSETS / "placeholder"
CATALOG = OUT_DIR / "catalog.json"
# Asset keys as the Flutter app sees them (relative to app/).
ASSET_PREFIX = "assets/audio/placeholder"

# Must match surahManifest in packages/salah_core/lib/src/content.dart.
AYAH_COUNTS = {
    1: 7, 93: 11, 94: 8, 95: 8, 97: 5, 102: 8, 103: 3, 105: 5, 106: 4,
    107: 7, 108: 3, 109: 6, 110: 3, 112: 4, 113: 5, 114: 6,
}

RATE = 16000          # Hz, mono, 16-bit
SILENCE_RATE = 8000
SILENCE_SECONDS = 10
SILENCE = ASSETS / f"silence_{SILENCE_SECONDS}s.wav"
MAX_TOTAL_BYTES = 4_200_000


def pitch_for(surah: int) -> float:
    """A distinct pitch per surah, a semitone apart, from A3 (220 Hz)."""
    order = sorted(AYAH_COUNTS).index(surah)
    return 220.0 * 2 ** (order / 12)


def duration_ms_for(surah: int, ayah: int) -> int:
    """1.0-1.5 s, varying by ayah so clips are not all alike."""
    return 1000 + ((surah * 7 + ayah * 13) % 3) * 250


def clip_name(surah: int, ayah: int) -> str:
    return f"{surah:03d}{ayah:03d}.wav"


def tone(freq: float, ms: int) -> bytes:
    n = RATE * ms // 1000
    blip = RATE * 120 // 1000          # last 120 ms: a fifth higher
    fade = RATE * 15 // 1000           # 15 ms fades, no clicks
    samples = []
    phase = 0.0
    for i in range(n):
        f = freq * 1.5 if i >= n - blip else freq
        phase += 2 * math.pi * f / RATE
        env = min(1.0, i / fade, (n - 1 - i) / fade)
        # Short gap just before the blip, so it reads as a separate mark.
        if n - blip - fade <= i < n - blip:
            env = 0.0
        samples.append(int(0.3 * 32767 * env * math.sin(phase)))
    return struct.pack(f"<{n}h", *samples)


def write_wav(path: Path, pcm: bytes, rate: int) -> None:
    """Writes atomically (temp file, then rename), so a cut-short run never
    leaves a truncated file that --if-missing would accept."""
    tmp = path.with_name(path.name + ".part")
    with wave.open(str(tmp), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(pcm)
    tmp.replace(path)


def expected_files() -> list[Path]:
    clips = [OUT_DIR / clip_name(s, a)
             for s, count in AYAH_COUNTS.items() for a in range(1, count + 1)]
    return clips + [SILENCE, CATALOG]


def build_catalog() -> dict:
    clips = [
        {
            "surah": surah,
            "ayah": ayah,
            "path": f"{ASSET_PREFIX}/{clip_name(surah, ayah)}",
            "durationMs": duration_ms_for(surah, ayah),
        }
        for surah, count in AYAH_COUNTS.items()
        for ayah in range(1, count + 1)
    ]
    return {
        "format": 1,
        "placeholder": True,
        "note": "PLACEHOLDER sine tones, not recitation. Generated by "
                "scripts/make_placeholder_audio.py. Real recordings: #18.",
        "codec": "PCM WAV mono 16-bit 16 kHz",
        "clips": clips,
    }


def main() -> None:
    p = argparse.ArgumentParser(description="Generate placeholder ayah tones.")
    p.add_argument("--if-missing", action="store_true",
                   help="do nothing if every output file already exists")
    args = p.parse_args()

    if args.if_missing and all(f.is_file() for f in expected_files()):
        return

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OUT_DIR.glob("*"):
        if old.suffix in {".m4a", ".wav", ".part"}:
            old.unlink()

    catalog = build_catalog()
    for c in catalog["clips"]:
        pcm = tone(pitch_for(c["surah"]), c["durationMs"])
        write_wav(REPO / "app" / c["path"], pcm, RATE)

    CATALOG.write_text(json.dumps(catalog, indent=1) + "\n")
    write_wav(SILENCE, b"\\x00\\x00" * SILENCE_RATE * SILENCE_SECONDS, SILENCE_RATE)

    total = sum(f.stat().st_size for f in expected_files())
    print(f"{len(catalog['clips'])} clips (wav), silence, catalog: "
          f"{total / 1024:.0f} KiB under {ASSETS}")
    if len(catalog["clips"]) != sum(AYAH_COUNTS.values()):
        sys.exit("error: clip count mismatch")
    if total > MAX_TOTAL_BYTES:
        sys.exit(f"error: {total} bytes, more than {MAX_TOTAL_BYTES}")


if __name__ == "__main__":
    main()
